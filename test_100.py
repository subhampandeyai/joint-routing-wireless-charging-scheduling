#  2.  VEHICLE AGENT
# ══════════════════════════════════════════════════════════════════════════════

class VehicleAgent:
    """
    Vehicle subproblem agent  (Section V of formulation).

    Decision variables:
      y^k ∈ [0,1]^R    continuous assignment weights  (M1)
      c^k ∈ [0,20]^N   continuous charging amounts    (M5)

    Key charging update [Eq. C]  (M4):
      c_feas_s  = min charge at s to keep SOC ≥ B_min  (mandatory)
      c_price_s = max(0, w_s − (π_s + μ_s)/ρ)          (price-optimal)
      c_s^k     = max(c_feas_s, c_price_s)

    Charging is computed AFTER routing, not before  (fixes update-order bug).

    Route:  greedy NN with pickup→delivery precedence  (M9)
    Price optimisation:  greedy look-back pre-charging  (M6)
    """

    def __init__(self, kid: int, data: DataLoader):
        self.kid  = kid
        self.data = data
        K, R, N   = data.n_veh, data.n_req, data.N

        self.B_init = float(data.vehicles.iloc[kid]['initial_battery_kWh'])

        # ── Decision variables ────────────────────────────────────────────
        self.y = self._sector_init(kid, K, R)   # (R,) in [0,1]
        self.c = np.zeros(N)                    # (N,) in [0, c_max]

        # ── Dual variables (broadcast by ConsensusAgent) ──────────────────
        self.lam = np.zeros(R)           # λ_r^k
        self.mu  = np.zeros(N)           # μ_s^k
        self.z   = np.full(R, 1.0 / K)  # z_r^k (consensus copy)
        self.w   = np.zeros(N)           # w_s^k (consensus copy)

        # ── Result storage ────────────────────────────────────────────────
        self.route         = [data.start, data.end]
        self.soc_profile   = [self.B_init, self.B_init]
        self.charge_events = []   # list of (node, kWh, soc_before, soc_after)

    # ── Sector initialisation (M3) ────────────────────────────────────────
    def _sector_init(self, kid, K, R) -> np.ndarray:
        """Initialise y^k with angular-sector affinity to break symmetry (M3)."""
        d    = self.data
        dxy  = d.xy[d.start]
        pxy  = d.xy[d.req_pickup]
        dist = np.linalg.norm(pxy - dxy, axis=1) + 1e-6
        ang  = np.arctan2(pxy[:,1]-dxy[1], pxy[:,0]-dxy[0])
        sec  = 2.0 * np.pi * kid / K
        aff  = (1.0/dist) * np.clip(1.0 + 0.85*np.cos(ang-sec), 0.05, 2.0)
        y    = aff / (aff.sum()+1e-9) * (R / K)
        return np.clip(y, 0.0, 1.0)

    # ── Main subproblem solve ─────────────────────────────────────────────
    def solve(self, rho: float):
        """
        One ADMM vehicle-subproblem update.

        Order of operations:
          1. Update y via proximal gradient (closed-form)
          2. Build greedy NN route from current y
          3. Compute c_feas from actual route SOC simulation
          4. Update c = max(c_feas, c_price)  [Eq. C]
          5. Final SOC simulation with c for reporting
        """
        # Step 1: y update
        self._update_y(rho)

        # Step 2: build route
        route = self._build_greedy_route()

        # Step 3: c_feas from route simulation
        c_feas = self._compute_c_feas(route)

        # Step 4: c = max(c_feas, c_price)  [Eq. C, M4]
        c_price = np.maximum(0.0,
                             self.w - (self.data.node_price + self.mu)
                             / (rho + 1e-8))
        c_price = np.clip(c_price, 0.0, self.data.c_max)
        self.c  = np.maximum(c_feas, c_price)

        # Step 5: simulate final SOC (sets self.route, self.soc_profile,
        #          self.charge_events)
        self._simulate_soc(route)

    # ── Step 1: y update ─────────────────────────────────────────────────
    def _update_y(self, rho: float):
        """
        Proximal gradient on assignment variable y^k.

        grad = α·cost_r/normalise + λ_r + ρ(y_r − z_r)

        Load-balance gradient deliberately omitted (M2):
        it causes ‖Y−Z‖ → √3 deadlock diagnosed analytically.
        """
        g_route = 1.0 * self.data.trip_km / 200.0          # (R,) normalised
        g_admm  = self.lam + rho * (self.y - self.z)        # (R,)
        step    = 1.0 / (rho + 1.0 + 1e-8)
        self.y  = np.clip(self.y - step * (g_route + g_admm), 0.0, 1.0)

    # ── Step 2: greedy NN route ───────────────────────────────────────────
    def _build_greedy_route(self) -> list:
        """
        Greedy nearest-neighbour pickup-delivery tour (M9).
        Select top ⌈R/K⌉+2 requests by y-score; enforce pickup→delivery (M7).
        Returns list of node IDs.
        """
        d       = self.data
        dm      = d.dist_mat
        K       = d.n_veh
        R_cap   = int(np.ceil(d.n_req / K)) + 2             # (M7)
        score   = self.y * (1.0 + 0.03 * d.req_priority)
        order   = np.argsort(-score)
        thresh  = max(0.10, 0.15 / K)

        assigned = []
        for r in order:
            if self.y[r] >= thresh:
                assigned.append(r)
                if len(assigned) >= R_cap:
                    break
        if not assigned:
            assigned = [order[0]]

        pend_p  = set(assigned)
        pend_d  = {}
        route   = [d.start]
        current = d.start

        for _ in range(4 * len(assigned) + 4):
            if not pend_p and not pend_d:
                break
            best = None; best_dist = np.inf; btype = None; br = None
            for r in pend_p:
                n = int(d.req_pickup[r]);   dist = dm[current, n]
                if dist < best_dist:
                    best_dist, best, btype, br = dist, n, 'P', r
            for r in pend_d:
                n = int(d.req_delivery[r]); dist = dm[current, n]
                if dist < best_dist:
                    best_dist, best, btype, br = dist, n, 'D', r
            if best is None:
                break
            route.append(best)
            if btype == 'P':
                pend_p.discard(br); pend_d[br] = best
            else:
                pend_d.pop(br, None)
            current = best

        route.append(d.end)
        return route

    # ── Step 3: c_feas from SOC simulation ───────────────────────────────
    def _compute_c_feas(self, route: list) -> np.ndarray:
        """
        Compute minimum feasibility charging (M4).

        Simulate SOC along route with NO charging.
        Whenever SOC < B_thr (35% B_max), charge at that node to 80% B_max.
        Price-aware look-back (M6): if a cheaper earlier node exists on the
        route AND pre-charging there would prevent this stop, use the earlier
        cheaper station instead.

        Returns c_feas: sparse array (N,) with needed kWh at each node.
        """
        d      = self.data
        dm     = d.dist_mat
        c_feas = np.zeros(d.N)
        soc    = self.B_init

        # Forward pass: identify where charging is needed
        needs = []   # (route_idx, soc_at_arrival, needed_kWh)
        soc_at = [self.B_init]
        for i in range(1, len(route)):
            energy = d.kappa * dm[route[i-1], route[i]]
            soc    = max(d.B_min, soc - energy)
            soc_at.append(soc)
            if soc < d.B_thr:
                target  = 0.80 * d.B_max
                needed  = max(0.0, (target - soc) / d.eta)
                needed  = min(needed, d.c_max)
                needs.append((i, soc, needed, route[i]))
                soc     = min(d.B_max, soc + d.eta * needed)

        if not needs:
            return c_feas                                   # no charging needed

        # Price-aware look-back (M6):
        # For each charging stop at node hi_node (price pi_hi),
        # check if charging earlier at lo_node (price pi_lo < pi_hi)
        # avoids the hi_node stop entirely.
        assigned_charge = {}   # route_idx → kWh
        for (i, soc_arr, needed, hi_node) in needs:
            pi_hi = d.node_price[hi_node]
            best_idx  = i
            best_price= pi_hi

            # Look back at candidate earlier stations on route
            for j in range(max(0, i-6), i):
                lo_node = route[j]
                if lo_node >= d.n_stat:
                    continue
                pi_lo = d.node_price[lo_node]
                if pi_lo >= best_price - 0.05:       # significant saving needed
                    continue
                # Check if pre-charging at j removes the need at i
                soc_after_pre = min(d.B_max,
                                    soc_at[j] + d.eta * needed)
                # Re-simulate soc from j to i with pre-charging
                soc_sim = soc_after_pre
                feasible = True
                for k in range(j+1, i+1):
                    e = d.kappa * dm[route[k-1], route[k]]
                    soc_sim = soc_sim - e
                    if soc_sim < d.B_min:
                        feasible = False; break
                if feasible and soc_sim >= d.B_thr:
                    best_idx   = j
                    best_price = pi_lo

            # Assign the needed charge to the chosen station
            if best_idx not in assigned_charge:
                assigned_charge[best_idx] = 0.0
            assigned_charge[best_idx] += needed

        # Write to c_feas array
        for idx, kwh in assigned_charge.items():
            node = route[idx]
            c_feas[node] = min(kwh, d.c_max)

        return c_feas

    # ── Step 5: simulate SOC with actual c ───────────────────────────────
    def _simulate_soc(self, route: list):
        """Run final SOC simulation with self.c; record charge_events."""
        d          = self.data
        dm         = d.dist_mat
        soc        = self.B_init
        soc_pr     = [soc]
        ch_ev      = []
        current    = route[0]

        for i in range(1, len(route)):
            node   = route[i]
            energy = d.kappa * dm[current, node]
            soc    = max(d.B_min, soc - energy)

            # Charge at this node if c[node] > 0
            amt = float(self.c[node])
            if amt > 0.01:
                amt    = min(amt, d.c_max, (d.B_max - soc) / d.eta)
                if amt > 0.01:
                    soc_b  = soc
                    soc    = min(d.B_max, soc + d.eta * amt)
                    ch_ev.append((node, amt, soc_b, soc))

            soc_pr.append(soc)
            current = node

        self.route         = route
        self.soc_profile   = soc_pr
        self.charge_events = ch_ev

    # ── Cost helpers ──────────────────────────────────────────────────────
    def route_cost(self) -> float:
        dm = self.data.dist_mat
        return float(sum(dm[self.route[i], self.route[i+1]]
                         for i in range(len(self.route)-1)))

    def charging_cost(self) -> float:
        return float(sum(self.data.node_price[n] * amt
                         for n, amt, _, _ in self.charge_events))

    def final_soc(self) -> float:
        return float(self.soc_profile[-1]) if self.soc_profile else self.B_init

    def min_soc(self) -> float:
        return float(min(self.soc_profile)) if self.soc_profile else self.B_init


