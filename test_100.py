#  4.  CONSENSUS AGENT
# ══════════════════════════════════════════════════════════════════════════════

def _proj_simplex(v: np.ndarray) -> np.ndarray:
    """Project v onto {x : Σx_i=1, x_i≥0}  (Duchi et al. 2008)."""
    n  = len(v)
    u  = np.sort(v)[::-1]
    cs = np.cumsum(u)
    rh = np.where(u > (cs - 1.0) / (np.arange(n) + 1.0))[0]
    if not len(rh):
        return np.ones(n) / n
    theta = (cs[rh[-1]] - 1.0) / (rh[-1] + 1.0)
    return np.maximum(v - theta, 0.0)


class ConsensusAgent:
    """
    Central consensus + dual update  (Sections VII–VIII of formulation).

    Manages:
      Z (K×R) — global assignment copies, simplex-feasible per request
      W (K×N) — global charging copies, capacity-feasible per station
      Λ (K×R) — dual variables for assignment
      M (K×N) — dual variables for charging

    Uses sparse W representation (only tracks non-zero stations) for memory
    efficiency with 602 stations × 10 vehicles.
    """

    def __init__(self, data: DataLoader, vehicles: list, stations: list):
        self.data     = data
        self.vehicles = vehicles
        self.stations = stations
        K, R, N       = data.n_veh, data.n_req, data.N

        self.Z   = np.full((K, R), 1.0 / K)
        self.W   = np.zeros((K, N))
        self.LAM = np.zeros((K, R))
        self.MU  = np.zeros((K, N))

        self.residuals = []
        self.primal_y  = []
        self.primal_c  = []
        self.dual_res  = []

    # ── Main update ───────────────────────────────────────────────────────
    def update(self, rho: float) -> float:
        """
        Full consensus + dual update.
        Returns r_prim = ‖Y−Z‖_F + ‖C−W‖_F.
        """
        K, R, N = self.data.n_veh, self.data.n_req, self.data.N

        Y = np.vstack([v.y for v in self.vehicles])    # (K,R)
        C = np.vstack([v.c for v in self.vehicles])    # (K,N)

        Z_old = self.Z.copy()
        W_old = self.W.copy()

        # Assignment consensus: simplex projection per request (Section VII)
        Z_new = np.zeros((K, R))
        for r in range(R):
            Z_new[:, r] = _proj_simplex(Y[:, r] + self.LAM[:, r] / rho)

        # Charging consensus: box projection per station (Section VII)
        # Only process stations with non-zero C or W to save time
        W_new  = np.zeros((K, N))
        active = np.where((C.sum(0) + self.W.sum(0)) > 0)[0]
        for s in active:
            tilde = C[:, s] + self.MU[:, s] / rho
            w_col = np.maximum(0.0, tilde)
            w_col = np.minimum(w_col, self.data.c_max)
            tot   = w_col.sum()
            if tot > self.data.C_max_s[s] and tot > 0:
                w_col *= self.data.C_max_s[s] / tot
            W_new[:, s] = w_col

        # Dual updates (Section VIII)
        LAM_new = self.LAM + rho * (Y - Z_new)
        MU_new  = self.MU  + rho * (C - W_new)

        # Residuals (Section IX)
        res_y  = np.linalg.norm(Y - Z_new)
        res_c  = np.linalg.norm(C - W_new)
        r_prim = res_y + res_c
        r_dual = rho * (np.linalg.norm(Z_new - Z_old)
                        + np.linalg.norm(W_new - W_old))

        self.primal_y.append(float(res_y))
        self.primal_c.append(float(res_c))
        self.residuals.append(float(r_prim))
        self.dual_res.append(float(r_dual))

        # Commit
        self.Z   = Z_new;   self.W   = W_new
        self.LAM = LAM_new; self.MU  = MU_new

        # Broadcast to vehicle agents
        for k, veh in enumerate(self.vehicles):
            veh.z   = self.Z[k, :]
            veh.w   = self.W[k, :]
            veh.lam = self.LAM[k, :]
            veh.mu  = self.MU[k, :]

        # Broadcast to station agents
        for s, sta in enumerate(self.stations):
            sta.w  = self.W[:, s]
            sta.mu = self.MU[:, s]

        return float(r_prim)

    # ── Final binary extraction (M1) ─────────────────────────────────────
    def extract_assignments(self) -> dict:
        """
        Argmax rounding with capacity-load penalty (M1 + M7).
        Most-certain requests assigned first; load penalty prevents
        all requests going to one vehicle.
        """
        K, R  = self.data.n_veh, self.data.n_req
        R_cap = int(np.ceil(R / K)) + 2
        load  = np.zeros(K, dtype=int)
        assign= {}
        for r in np.argsort(-self.Z.max(axis=0)):
            pen    = 0.10 * np.maximum(load - R_cap + 1, 0)
            k      = int(np.argmax(self.Z[:, r] - pen))
            assign[r] = k
            load[k]  += 1
        return assign


