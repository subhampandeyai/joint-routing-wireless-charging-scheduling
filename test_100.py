#  3.  CHARGING STATION AGENT
# ══════════════════════════════════════════════════════════════════════════════

class ChargingStationAgent:
    """
    Station subproblem  (Section VI of formulation).

    min_{c_s^k ≥ 0}  π_s · Σ_k c_s^k
                     + Σ_k [ μ_s^k(c_s^k − w_s^k) + (ρ/2)(c_s^k−w_s^k)² ]
    s.t.  Σ_k c_s^k ≤ Ĉ_s

    Closed-form:  c_s^{k*} = max(0, w_s^k − (π_s + μ_s^k)/ρ)
    Followed by proportional capacity projection if Σ_k c_s^{k*} > Ĉ_s.
    """

    def __init__(self, sid: int, data: DataLoader):
        self.sid   = sid
        self.pi    = float(data.node_price[sid])
        self.C_max = float(data.C_max_s[sid])
        self.c_max = data.c_max
        K          = data.n_veh
        self.c     = np.zeros(K)
        self.mu    = np.zeros(K)
        self.w     = np.zeros(K)

    def solve(self, rho: float):
        c_new = np.maximum(0.0,
                           self.w - (self.pi + self.mu) / (rho + 1e-8))
        c_new = np.minimum(c_new, self.c_max)
        total = c_new.sum()
        if total > self.C_max and total > 0:
            c_new *= self.C_max / total
        self.c = c_new


