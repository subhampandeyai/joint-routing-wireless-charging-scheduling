#  5.  ADMM SOLVER
# ══════════════════════════════════════════════════════════════════════════════

class ADMMSolver:
    """
    Orchestrates the ADMM algorithm  (Section IX of formulation).

    Loop:
      Step 2: Vehicle subproblems (y update → route → c_feas → c update)
      Step 3: Station subproblems (c_s update)
      Step 4: Consensus (Z, W projections)
      Step 5: Dual update (Λ, M)
      Step 6: Residual check

    Adaptive ρ (M8): every 10 iterations, rescale ρ by 1.5
    if r_prim/r_dual imbalance > 10×.
    """

    def __init__(self, data: DataLoader,
                 rho: float     = 2.0,
                 max_iter: int  = 400,
                 tol: float     = 1e-2):
        self.data     = data
        self.rho      = rho
        self.max_iter = max_iter
        self.tol      = tol

        # Initialise agents  (Step 1: z=w=λ=μ=0)
        self.vehicles  = [VehicleAgent(k, data) for k in range(data.n_veh)]
        self.stations  = [ChargingStationAgent(s, data)
                          for s in range(data.n_stat)]
        self.consensus = ConsensusAgent(data, self.vehicles, self.stations)
        self.iter_log  = []

    # ── Main solve ────────────────────────────────────────────────────────
    def solve(self) -> dict:
        W = 72
        print(f"\n{'═'*W}")
        print("  ADMM IoEV — Joint Routing & Wireless Charging")
        print(f"{'═'*W}")
        print(f"  ρ={self.rho}  max_iter={self.max_iter}  ε={self.tol}")
        print(f"  K={self.data.n_veh}  R={self.data.n_req}  "
              f"S={self.data.n_stat}")
        print(f"{'─'*W}")
        print(f"  {'Iter':>5}  {'‖r_prim‖':>12}  {'‖y−z‖':>9}  "
              f"{'‖c−w‖':>10}  {'ρ':>6}  {'Obj':>12}")
        print(f"{'─'*W}")

        t0 = time.time()

        for it in range(1, self.max_iter + 1):

            # Step 2: Vehicle subproblems
            for veh in self.vehicles:
                veh.solve(self.rho)

            # Step 3: Station subproblems
            for sta in self.stations:
                sta.solve(self.rho)

            # Steps 4+5: Consensus + Dual
            r_prim = self.consensus.update(self.rho)

            # Step 6: adaptive ρ (M8) every 10 iters
            if it % 10 == 0 and self.consensus.dual_res:
                r_dual = self.consensus.dual_res[-1]
                if r_prim > 10 * (r_dual + 1e-12):
                    self.rho = min(self.rho * 1.5, 100.0)
                elif r_dual > 10 * (r_prim + 1e-12):
                    self.rho = max(self.rho / 1.5, 0.1)

            obj   = self._objective()
            res_y = self.consensus.primal_y[-1]
            res_c = self.consensus.primal_c[-1]
            self.iter_log.append({
                'iter':it, 'residual':r_prim,
                'res_y':res_y, 'res_c':res_c,
                'obj':obj,     'rho':self.rho
            })

            if it <= 5 or it % 20 == 0 or r_prim < self.tol:
                print(f"  {it:>5}  {r_prim:>12.6f}  {res_y:>9.6f}  "
                      f"{res_c:>10.6f}  {self.rho:>6.2f}  {obj:>12.4f}")

            if r_prim < self.tol and it >= 10:
                print(f"\n  ✓ Converged  iter={it}  ‖r‖={r_prim:.7f}")
                break

        print(f"{'─'*W}")
        print(f"  Elapsed={time.time()-t0:.2f}s  "
              f"ρ_final={self.rho:.3f}  "
              f"‖r‖_final={self.consensus.residuals[-1]:.7f}")

        return self._extract()

    # ── Objective ─────────────────────────────────────────────────────────
    def _objective(self) -> float:
        return sum(v.route_cost() + v.charging_cost() for v in self.vehicles)

    # ── Extract final integer-feasible solution ───────────────────────────
    def _extract(self) -> dict:
        """
        1. Binary-round y via argmax (M1).
        2. Discretise c to {0,5,15,20} kWh (M5, applied here not during ADMM).
        3. Rebuild routes + SOC with hard binary assignment.
        """
        assign    = self.consensus.extract_assignments()
        k2r       = {k: [] for k in range(self.data.n_veh)}
        for r in assign.keys():
            k = assign[r]
            k2r[k].append(r)

        levels = self.data.charge_levels
        for k, veh in enumerate(self.vehicles):
            # Hard binary y
            y_bin = np.zeros(self.data.n_req)
            for r in k2r[k]:
                y_bin[r] = 1.0
            veh.y = y_bin

            # Discretise c (M5)
            veh.c = levels[np.argmin(
                np.abs(veh.c[:, None] - levels[None, :]), axis=1
            )].astype(float)

            # Rebuild route with hard assignment + discretised c
            route = veh._build_greedy_route()
            veh._simulate_soc(route)

        return {
            'assignments'   : assign,
            'k_to_requests' : k2r,
            'routes'        : {k: v.route         for k,v in enumerate(self.vehicles)},
            'soc_profiles'  : {k: v.soc_profile   for k,v in enumerate(self.vehicles)},
            'charge_events' : {k: v.charge_events  for k,v in enumerate(self.vehicles)},
            'final_soc'     : {k: v.final_soc()   for k,v in enumerate(self.vehicles)},
            'min_soc'       : {k: v.min_soc()     for k,v in enumerate(self.vehicles)},
            'route_costs'   : {k: v.route_cost()  for k,v in enumerate(self.vehicles)},
            'charging_costs': {k: v.charging_cost() for k,v in enumerate(self.vehicles)},
            'total_obj'     : self._objective(),
            'residuals'     : self.consensus.residuals,
            'primal_y'      : self.consensus.primal_y,
            'primal_c'      : self.consensus.primal_c,
            'dual_res'      : self.consensus.dual_res,
            'iter_log'      : self.iter_log,
            'n_iters'       : len(self.iter_log),
        }


