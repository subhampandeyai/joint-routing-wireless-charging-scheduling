class DataLoader:
    """Loads, validates and pre-computes all dataset quantities."""

    def __init__(self, req_file: str = "requests_.csv"):
        up = DATA_DIR
        self.nodes    = pd.read_csv(f"{up}/nodes.csv")
        self.requests = pd.read_csv(f"{up}/{req_file}")
        self.vehicles = pd.read_csv(f"{up}/vehicles.csv")
        self.stations = pd.read_csv(f"{up}/charging_stations.csv")
        self.prices   = pd.read_csv(f"{up}/price_schedule.csv")
        self.params_df= pd.read_csv(f"{up}/parameters.csv")

        # Distance matrix (N×N km)
        dm_raw        = pd.read_csv(f"{up}/distance_matrix.csv", index_col=0)
        self.dist_mat = dm_raw.values.astype(np.float64)
        self.N        = self.dist_mat.shape[0]   # 602

        P = dict(zip(self.params_df['parameter'],
                     self.params_df['value'].astype(float)))

        # Battery parameters (Section I of formulation)
        self.B_max  = P['battery_capacity_kWh']          # 30 kWh
        self.kappa  = float(self.vehicles[
                            'max_energy_consumption_kWh_per_km'].iloc[0])
        self.eta    = P['charging_efficiency']            # 0.90
        self.B_min  = 0.10 * self.B_max                  # 3 kWh (10% floor)
        self.B_thr  = 0.35 * self.B_max                  # 10.5 kWh charge trigger

        # Counts
        self.n_req  = len(self.requests)
        self.n_veh  = len(self.vehicles)
        self.n_stat = len(self.stations)                  # 602

        # Charging levels from model_config.json: {0, 5, 15, 20} kWh
        self.charge_levels = np.array([0.0, 5.0, 15.0, 20.0])
        self.c_max         = 20.0                        # max per visit

        # Price per station: rescaled to paper's stated [0.50, 1.00] $/kWh
        peak_mult = float(self.prices['price_multiplier'].max())
        raw_p     = self.stations['base_price_per_kWh'].values * peak_mult
        lo, hi    = raw_p.min(), raw_p.max()
        self.node_price = (0.50 + (raw_p - lo) / (hi - lo + 1e-9) * 0.50
                           ).astype(float)               # (N,)

        # Station capacity: large_allowable × n_veh (per-station ceiling)
        self.C_max_s = (self.stations['large_allowable_kWh'].values
                        * self.n_veh).astype(float)      # (N,)

        # Node coordinates (for plotting)
        self.xy = self.nodes[['x_km', 'y_km']].values   # (N,2)

        # Request arrays
        self.req_pickup   = self.requests['pickup_node_id'].values    # (R,)
        self.req_delivery = self.requests['delivery_node_id'].values  # (R,)
        self.req_priority = self.requests['service_priority'].values.astype(float)

        # Depot
        self.start = int(self.vehicles['start_node_id'].iloc[0])  # 0
        self.end   = int(self.vehicles['end_node_id'].iloc[0])    # 1

        # Pre-computed: direct trip energy per request (used in gradients)
        dm = self.dist_mat
        p  = self.req_pickup;  d = self.req_delivery
        self.trip_km     = dm[self.start, p] + dm[p, d] + dm[d, self.end]
        self.trip_energy = self.trip_km * self.kappa

        self._print_summary()

    def _print_summary(self):
        avg_load = self.trip_energy.mean() * self.n_req / self.n_veh
        print(f"[Data]  N={self.N}  R={self.n_req}  K={self.n_veh}  S={self.n_stat}")
        print(f"        B_max={self.B_max:.0f} kWh  κ={self.kappa:.6f} kWh/km  "
              f"η={self.eta:.2f}  B_min={self.B_min:.1f} kWh  B_thr={self.B_thr:.1f} kWh")
        print(f"        Price: ${self.node_price.min():.3f}–"
              f"${self.node_price.max():.3f}/kWh")
        print(f"        Trip energy: {self.trip_energy.min():.2f}–"
              f"{self.trip_energy.max():.2f} kWh  "
              f"avg load/vehicle={avg_load:.2f} kWh "
              f"({'NEEDS CHARGING' if avg_load>self.B_max-self.B_min else 'feasible without charging'})")


